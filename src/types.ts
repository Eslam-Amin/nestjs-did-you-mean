import type { ModuleMetadata, Type } from '@nestjs/common';

/**
 * Represents a registered route candidate in the NestJS application.
 */
export interface RouteDefinition {
  method: string;
  path: string;
  normalizedPattern: string;
  segments: string[];
  summary?: string;
  operationId?: string;
  controllerName?: string;
  methodName?: string;
}

/**
 * A suggested route returned to the caller.
 */
export interface RouteSuggestion {
  method: string;
  path: string;
  score: number;
  isMethodMismatch: boolean;
  summary?: string;
  operationId?: string;
}

/**
 * Standard 404 response payload with suggestions.
 */
export interface DidYouMeanResponsePayload {
  statusCode: number;
  error: string;
  message: string;
  suggestions: RouteSuggestion[];
}

/**
 * Context provided to response formatters.
 */
export interface FormatContext {
  req: any;
  res: any;
  method: string;
  url: string;
  path: string;
  suggestions: RouteSuggestion[];
  statusCode: number;
  error: string;
  message: string;
}

/**
 * Options for configuring DidYouMeanModule.
 */
export interface DidYouMeanModuleOptions {
  /**
   * Explicitly enable or disable route suggestions, or provide a function evaluated per request.
   * Default: enabled when process.env.NODE_ENV !== 'production'
   */
  enabled?: boolean | ((req: any) => boolean);

  /**
   * List of environment names where suggestions are enabled.
   * Example: ['development', 'local', 'test', 'staging']
   */
  enabledEnvironments?: string[];

  /**
   * Minimum similarity score (0.0 to 1.0) required for a route to be suggested.
   * Default: 0.4
   */
  threshold?: number;

  /**
   * Maximum number of route suggestions to return.
   * Default: 3
   */
  maxSuggestions?: number;

  /**
   * Optional OpenAPI/Swagger document generated by @nestjs/swagger (SwaggerModule.createDocument).
   * When provided, routes and summaries/operationIds are extracted from the spec.
   */
  swaggerDoc?: any;

  /**
   * Optional global route prefix (e.g. 'api' or '/api/v1').
   * If not set, it is auto-detected from NestJS application config where available.
   */
  globalPrefix?: string;

  /**
   * Exclude routes matching these string paths or regular expressions.
   */
  excludePaths?: (string | RegExp)[];

  /**
   * Response format: 'json', 'html', 'auto' (content negotiation via Accept header), or a custom formatter function.
   * Default: 'auto'
   */
  format?: 'json' | 'html' | 'auto' | ((context: FormatContext) => any);

  /**
   * Whether to include HTTP method compatibility in scoring.
   * Default: true
   */
  includeMethodInScore?: boolean;

  /**
   * Whether to automatically register DidYouMeanFilter as a global APP_FILTER.
   * Default: true
   */
  isGlobalFilter?: boolean;

  /**
   * Optional custom ranking function.
   */
  customRanker?: (
    target: { method: string; path: string },
    candidates: RouteDefinition[],
    options: DidYouMeanModuleOptions,
  ) => RouteSuggestion[];
}

/**
 * Factory interface for creating module options asynchronously.
 */
export interface DidYouMeanOptionsFactory {
  createDidYouMeanOptions(): Promise<DidYouMeanModuleOptions> | DidYouMeanModuleOptions;
}

/**
 * Asynchronous options for DidYouMeanModule.forRootAsync.
 */
export interface DidYouMeanModuleAsyncOptions extends Pick<ModuleMetadata, 'imports'> {
  useExisting?: Type<DidYouMeanOptionsFactory>;
  useClass?: Type<DidYouMeanOptionsFactory>;
  useFactory?: (...args: any[]) => Promise<DidYouMeanModuleOptions> | DidYouMeanModuleOptions;
  inject?: any[];
}
